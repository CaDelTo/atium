import { createRule } from "../create-rule.js";
import type { AtiumCatalogDocs } from "../create-rule.js";
import { FRAGILE_SELECTOR_DEFAULTS } from "../defaults.js";

/** Code of the rule that reports fragile CSS selectors (03-linter.md §11.3, E2E002). */
export const RULE_FRAGILE_CSS_SELECTOR = "E2E002";

/** Options of `atium/no-fragile-css-selector`. */
export interface FragileSelectorOptions {
  /** A selector with this many combinators or more is reported. */
  readonly depth: number;
}

/**
 * `atium/no-fragile-css-selector` (E2E002): reports a CSS selector in
 * `locator()`, `$()` or `cy.get()` that depends on the structure of the page —
 * `:nth-child` or `:nth-of-type`, `depth` or more combinators, a class
 * generated by CSS-in-JS or an id with a numeric sequence (03-linter.md §11.3).
 * One finding per selector, for its first reason in that order. In a file of
 * `pageObjectDirs`, the same selector is reported only where it first appears.
 */
export const noFragileCssSelector = createRule<
  [FragileSelectorOptions],
  "positionalPseudoClass" | "tooManyCombinators" | "generatedClass" | "numericId",
  AtiumCatalogDocs
>({
  name: "no-fragile-css-selector",
  meta: {
    type: "problem",
    docs: {
      description: "Disallow CSS selectors that depend on the structure of the page",
      code: RULE_FRAGILE_CSS_SELECTOR,
      severity: "warning",
      category: "selectors",
      confidence: "medium",
      source: "rule",
      recommended: true,
    },
    schema: [
      {
        type: "object",
        properties: { depth: { type: "integer", minimum: 1 } },
        additionalProperties: false,
      },
    ],
    messages: {
      positionalPseudoClass:
        "`:{{pseudoClass}}` picks an element by its position, which breaks when the page adds or reorders siblings. Use a role, label, text or test id.",
      tooManyCombinators:
        "This selector chains {{count}} combinators (the limit is {{depth}}), so any change to the page structure breaks it. Use a role, label, text or test id.",
      generatedClass:
        "`.{{className}}` is a class generated by a CSS-in-JS library and changes between builds. Use a role, label, text or test id.",
      numericId:
        "`#{{id}}` looks generated and may change between runs. Use a role, label, text or test id.",
    },
  },
  defaultOptions: [FRAGILE_SELECTOR_DEFAULTS],
  create: () => ({}),
});
