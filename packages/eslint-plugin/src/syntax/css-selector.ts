import { tokenize } from "parsel-js";
import type { AttributeToken, Token } from "parsel-js";
import {
  GENERATED_CLASS_PATTERNS,
  NUMERIC_ID_PATTERN,
  POSITIONAL_PSEUDO_CLASSES,
  SELECTOR_PREFIXES,
} from "../defaults.js";
import { isOneOf } from "./ast.js";

/** What one complex selector of a CSS list uses: `a > b` in `a > b, c`. */
export interface CssSegment {
  /** Positional pseudo-classes, without the colon. */
  readonly positionalPseudoClasses: readonly string[];
  /** Number of combinators. */
  readonly combinators: number;
  /** Ids, without the `#`. */
  readonly ids: readonly string[];
  /** Ids with a numeric sequence. */
  readonly numericIds: readonly string[];
  /** Classes, without the dot. */
  readonly classes: readonly string[];
  /** Classes generated by a CSS-in-JS library. */
  readonly generatedClasses: readonly string[];
  /** Type selectors, in lowercase. */
  readonly types: readonly string[];
  /** Attribute names, in lowercase. */
  readonly attributes: readonly string[];
}

interface MutableSegment {
  positionalPseudoClasses: string[];
  combinators: number;
  ids: string[];
  numericIds: string[];
  classes: string[];
  generatedClasses: string[];
  types: string[];
  attributes: string[];
}

function emptySegment(): MutableSegment {
  return {
    positionalPseudoClasses: [],
    combinators: 0,
    ids: [],
    numericIds: [],
    classes: [],
    generatedClasses: [],
    types: [],
    attributes: [],
  };
}

/**
 * Tokens of a CSS selector, without the `css=` prefix, or `undefined` when it
 * does not tokenize or the tokens do not form a selector list: an empty item,
 * or a combinator at the start, at the end or next to another one, as in
 * Playwright's `a >> b`.
 *
 * Only parsel's tokenizer runs: its `parse` nests the tree with a cost
 * quadratic in the number of combinators. The tokenizer is also superlinear
 * with many strings or parentheses, so callers cap the length of the text
 * first (`SELECTOR_MAX_LENGTH`).
 *
 * @param text - The selector, trimmed.
 * @returns The tokens, or `undefined` when the text is not a CSS selector list.
 */
export function cssTokens(text: string): readonly Token[] | undefined {
  const selector = text.startsWith(SELECTOR_PREFIXES.css)
    ? text.slice(SELECTOR_PREFIXES.css.length)
    : text;
  let tokens: Token[];
  try {
    tokens = tokenize(selector);
  } catch {
    // parsel throws on any sequence it does not recognize: not CSS, so unknown.
    return undefined;
  }
  return isSelectorList(tokens) ? tokens : undefined;
}

function isSelectorList(tokens: readonly Token[]): boolean {
  let compound = false;
  for (const token of tokens) {
    if (token.type === "comma" || token.type === "combinator") {
      if (!compound) {
        return false;
      }
      compound = false;
    } else {
      compound = true;
    }
  }
  return compound;
}

function addPseudoClass(segment: MutableSegment, name: string): void {
  const lower = name.toLowerCase();
  if (isOneOf(POSITIONAL_PSEUDO_CLASSES, lower)) {
    segment.positionalPseudoClasses.push(lower);
  }
}

// Universal selectors and pseudo-elements say nothing about fragility, and
// commas split segments before this point.
function addToken(segment: MutableSegment, token: Token): void {
  if (token.type === "combinator") {
    segment.combinators += 1;
  } else if (token.type === "id") {
    addId(segment, token.content.slice(1));
  } else if (token.type === "class") {
    addClass(segment, token.content.slice(1));
  } else if (token.type === "type") {
    segment.types.push(token.name.toLowerCase());
  } else if (token.type === "attribute") {
    segment.attributes.push(token.name.toLowerCase());
  } else if (token.type === "pseudo-class") {
    addPseudoClass(segment, token.name);
  }
}

function addId(segment: MutableSegment, id: string): void {
  segment.ids.push(id);
  if (NUMERIC_ID_PATTERN.test(id)) {
    segment.numericIds.push(id);
  }
}

function addClass(segment: MutableSegment, name: string): void {
  segment.classes.push(name);
  if (GENERATED_CLASS_PATTERNS.some((pattern) => pattern.test(name))) {
    segment.generatedClasses.push(name);
  }
}

/**
 * Splits the tokens of a selector list into its complex selectors and
 * records what each one uses. Pseudo-class arguments, such as the `li` of
 * `:has(li)`, are not analyzed.
 *
 * @param tokens - Tokens of a selector list, from {@link cssTokens}.
 * @returns One segment per complex selector of the list.
 */
export function cssSegments(tokens: readonly Token[]): readonly CssSegment[] {
  let current = emptySegment();
  const segments: MutableSegment[] = [current];
  for (const token of tokens) {
    if (token.type === "comma") {
      current = emptySegment();
      segments.push(current);
    } else {
      addToken(current, token);
    }
  }
  return segments;
}

const DOUBLE_QUOTE = '"';
const SINGLE_QUOTE = "'";

function quotedValue(value: string): string {
  if (value.startsWith(DOUBLE_QUOTE)) {
    return value;
  }
  if (value.startsWith(SINGLE_QUOTE)) {
    const inner = value.slice(1, -1);
    // A double quote inside would need an escape: keep the original quotes.
    return inner.includes(DOUBLE_QUOTE) ? value : `${DOUBLE_QUOTE}${inner}${DOUBLE_QUOTE}`;
  }
  return `${DOUBLE_QUOTE}${value}${DOUBLE_QUOTE}`;
}

function serializeAttribute(token: AttributeToken): string {
  if (token.namespace !== undefined || token.content.includes("\\")) {
    // Namespaces and escapes are rare and easy to break: keep them as written.
    return token.content;
  }
  const name = token.name.toLowerCase();
  if (token.operator === undefined || token.value === undefined) {
    return `[${name}]`;
  }
  const flag = token.caseSensitive === undefined ? "" : ` ${token.caseSensitive}`;
  return `[${name}${token.operator}${quotedValue(token.value)}${flag}]`;
}

function serializeToken(token: Token): string {
  if (token.type === "comma") {
    return ", ";
  }
  if (token.type === "combinator") {
    return token.content === " " ? " " : ` ${token.content} `;
  }
  if (token.type === "type") {
    return token.namespace === undefined ? token.content.toLowerCase() : token.content;
  }
  return token.type === "attribute" ? serializeAttribute(token) : token.content;
}

/**
 * Serializes the tokens of a selector list in a canonical form: one space
 * around combinators and after commas, attribute values in double quotes, and
 * type and attribute names in lowercase. Kept as written: an attribute with a
 * namespace or an escape, a single-quoted value that contains a double quote,
 * a type with a namespace, and pseudo-classes with their arguments.
 *
 * @param tokens - Tokens of a selector list, from {@link cssTokens}.
 * @returns The normalized selector.
 */
export function serializeCss(tokens: readonly Token[]): string {
  return tokens.map(serializeToken).join("");
}
