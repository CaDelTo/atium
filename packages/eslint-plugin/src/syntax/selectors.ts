import type { LocatorQuery } from "./locators.js";

/**
 * Level of a locator in the selector hierarchy (06-selector-advisor.md §14.1),
 * from 5, the most robust, to 1, the most fragile.
 */
export type SelectorLevel = 1 | 2 | 3 | 4 | 5;

/** What a CSS selector uses, for E2E002 and the classification (03-linter.md §11.3). */
export interface CssAnalysis {
  /** Discriminant. */
  readonly kind: "css";
  /** Positional pseudo-classes it uses, such as `nth-child`, without the colon. */
  readonly positionalPseudoClasses: readonly string[];
  /** Combinators of its longest complex selector; in a list, the largest count of any item. */
  readonly combinators: number;
  /** Every id, without the `#`. */
  readonly ids: readonly string[];
  /** The ids with a numeric sequence; a subset of `ids`. */
  readonly numericIds: readonly string[];
  /** Every class, without the dot. */
  readonly classes: readonly string[];
  /** The classes generated by a CSS-in-JS library; a subset of `classes`. */
  readonly generatedClasses: readonly string[];
  /** Every type selector, such as `button`, in lowercase. */
  readonly types: readonly string[];
  /** The name of every attribute selector, such as `data-testid`, in lowercase. */
  readonly attributes: readonly string[];
}

/** What an XPath selector uses, for E2E003 and the classification (03-linter.md §11.3). */
export interface XPathAnalysis {
  /** Discriminant. */
  readonly kind: "xpath";
  /** Predicates that pick by position, such as `[2]`, `[last()]` or `[position()=1]`. */
  readonly positionalPredicates: number;
  /** Whether the path starts at the root of the document, such as `/html/body/div`. */
  readonly absolute: boolean;
  /** The name of every attribute it tests, such as `data-testid` in `[@data-testid='x']`. */
  readonly attributes: readonly string[];
}

/** A selector that is neither CSS that parses nor XPath, such as `text=Pay` or `a >> b`. */
export interface UnknownSelector {
  /** Discriminant. */
  readonly kind: "unknown";
}

/** The result of {@link analyzeSelector}. */
export type SelectorAnalysis = CssAnalysis | XPathAnalysis | UnknownSelector;

/** Options of {@link classifyLocator}. */
export interface ClassifyOptions {
  /** `settings.atium.i18n`: a locator by visible text drops below the test id. */
  readonly i18n: boolean;
}

/**
 * The text of the selector of a query, when its first argument is a string
 * literal or a template without `${}`.
 *
 * @param query - A locator query.
 * @returns The text, or `undefined` when the argument is missing, a spread or
 *   not a literal.
 */
export function selectorText(query: LocatorQuery): string | undefined {
  throw new Error(`not implemented: ${query.method}`);
}

/**
 * Analyzes a selector string as CSS or XPath (03-linter.md §11.3, E2E002 and
 * E2E003). A text is XPath when it starts with `xpath=`, `/`, `(` or `..`, as
 * Playwright reads it; otherwise it is CSS, with an optional `css=` prefix.
 *
 * It never throws: a selector that does not parse, another Playwright engine
 * such as `text=` or `role=`, a chain with `>>` or a Cypress alias such as
 * `@user` is `unknown`. It runs in time linear in the length of the text.
 *
 * @param text - The selector.
 * @returns What the selector uses.
 */
export function analyzeSelector(text: string): SelectorAnalysis {
  throw new Error(`not implemented: ${text}`);
}

/**
 * Classifies a locator query in the hierarchy of 06-selector-advisor.md §14.1.
 *
 * A `getBy*` is classified by its method, whatever its argument: a
 * `getByRole` with `name` is 5 and `getByTestId` is 3. `locator`, `$` and
 * `cy.get` are classified by their selector: a test id attribute is 3, a
 * stable id or attribute is 2, and a selector with only types and classes, or
 * with any pattern of E2E002 or E2E003, is 1. When parts of a selector have
 * different levels, the lowest wins.
 *
 * @param query - A locator query.
 * @param options - Whether visible text is penalized (`i18n`).
 * @returns The level, or `undefined` when the selector is not a literal, is
 *   `unknown`, or the method is a `getBy*` that the hierarchy does not list.
 */
export function classifyLocator(
  query: LocatorQuery,
  options: ClassifyOptions,
): SelectorLevel | undefined {
  throw new Error(`not implemented: ${query.method} ${String(options.i18n)}`);
}

/**
 * Normalizes a selector so that E2E007 finds the same selector across files
 * (03-linter.md §11.4).
 *
 * CSS is serialized again from its syntax tree: whitespace collapsed, one
 * space around combinators and after commas, attribute values in double
 * quotes, and type and attribute names in lowercase. Classes, ids and values
 * keep their case, and nothing is reordered. XPath and unknown selectors are
 * trimmed, with runs of whitespace outside quotes collapsed to one space.
 *
 * It never throws, it is idempotent and it runs in time linear in the length
 * of the text.
 *
 * @param text - The selector.
 * @returns The normalized selector.
 */
export function normalizeSelector(text: string): string {
  throw new Error(`not implemented: ${text}`);
}
